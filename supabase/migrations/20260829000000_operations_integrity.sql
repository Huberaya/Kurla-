-- 1. Keep one current shipment per order before enabling upsert(order_id).
DO $$
DECLARE
  duplicate RECORD;
  keeper UUID;
  old_shipment UUID;
BEGIN
  FOR duplicate IN
    SELECT order_id, array_agg(id ORDER BY updated_at DESC NULLS LAST, created_at DESC NULLS LAST, id) AS shipment_ids
    FROM public.shipments
    GROUP BY order_id
    HAVING COUNT(*) > 1
  LOOP
    keeper := duplicate.shipment_ids[1];
    FOREACH old_shipment IN ARRAY duplicate.shipment_ids[2:array_length(duplicate.shipment_ids, 1)]
    LOOP
      UPDATE public.shipping_events SET shipment_id = keeper WHERE shipment_id = old_shipment;
      DELETE FROM public.shipments WHERE id = old_shipment;
    END LOOP;
  END LOOP;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS idx_shipments_order_id_unique
  ON public.shipments(order_id);

ALTER TABLE public.shipments DROP CONSTRAINT IF EXISTS shipments_status_check;
ALTER TABLE public.shipments
  ADD CONSTRAINT shipments_status_check CHECK (
    status IN ('preparing', 'label_created', 'shipped', 'in_transit', 'out_for_delivery', 'delivered', 'failed')
  );


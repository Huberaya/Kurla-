-- 3. Validate that historical operational identifiers are compatible with the
-- UUID columns used by the service. The application now generates UUIDs for
-- all new records; malformed legacy rows require manual remediation rather
-- than an implicit destructive cast.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM public.notifications WHERE id IS NULL)
     OR EXISTS (SELECT 1 FROM public.returns WHERE id IS NULL)
     OR EXISTS (SELECT 1 FROM public.support_tickets WHERE id IS NULL)
     OR EXISTS (SELECT 1 FROM public.support_messages WHERE id IS NULL) THEN
    RAISE EXCEPTION 'KURLA operations integrity failed: null operational identifier';
  END IF;
END $$;
